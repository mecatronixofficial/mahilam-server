import "reflect-metadata";
import { verifyResourcePersistence } from "./helpers/crm-persistence-checks.mjs";
import { test } from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { Client } from "pg";
import { PrismaPg } from "@prisma/adapter-pg";
import { PrismaClient } from "../dist/generated/prisma/client.js";
import { SequenceService } from "../dist/prisma/sequence.service.js";
import { EnquiriesService } from "../dist/enquiries/enquiries.service.js";
import { AdmissionsService } from "../dist/admissions/admissions.service.js";
import { CrmService } from "../dist/crm/crm.service.js";
import { FeesService } from "../dist/fees/fees.service.js";
import { StudentsService } from "../dist/students/students.service.js";
import { schoolDay } from "../dist/common/utils/school-time.js";
import { randomUUID } from "node:crypto";
// Only a deliberately named, empty, disposable local database is accepted.
// The configured school DATABASE_URL is never used as a fallback.
test("PostgreSQL: migrate and persist the complete admission workflow, concurrency, rollback and financial history", {skip: !process.env.CRM_TEST_DATABASE_URL, timeout: 180_000}, async () => {
  const url = new URL(process.env.CRM_TEST_DATABASE_URL);
  assert.ok(["localhost","127.0.0.1","[::1]"].includes(url.hostname),"Only disposable local PostgreSQL is authorized");
  assert.match(url.pathname,/^\/mahilam_crm_test_[a-zA-Z0-9_]+$/,"Database must have an explicit test-only name");
  const control = new Client({connectionString:url.href,connectionTimeoutMillis:5000});
  let prisma;
  await control.connect();
  try {
    const existing = await control.query("SELECT count(*)::int AS count FROM information_schema.tables WHERE table_schema = 'public'");
    assert.equal(existing.rows[0].count,0,"Refusing to migrate or reset a nonempty test database");
    const root = fileURLToPath(new URL("../",import.meta.url));
    await promisify(execFile)(process.execPath,["run",resolve(root,"node_modules/prisma/build/index.js"),"migrate","deploy"],{cwd:root,env:{...process.env,DATABASE_URL:url.href},windowsHide:true,timeout:60000,maxBuffer:2*1024*1024});
    prisma = new PrismaClient({adapter:new PrismaPg({connectionString:url.href})});
    await prisma.$connect(); await prisma.$queryRaw`SELECT 1`;
    const admin = await prisma.user.create({data:{name:"Integration Admin",email:randomUUID()+"@example.test",passwordHash:"test-fixture-not-a-login",role:"ADMIN"}});
    const counsellor = await prisma.user.create({data:{name:"Integration Counsellor",email:randomUUID()+"@example.test",passwordHash:"test-fixture-not-a-login",role:"COUNSELLOR"}});
    const teacher = await prisma.user.create({data:{name:"Integration Teacher",email:randomUUID()+"@example.test",passwordHash:"test-fixture-not-a-login",role:"TEACHER"}});
    const actor = {...admin,sub:admin.id}, staff = {...counsellor,sub:counsellor.id};
    const year = await prisma.academicYear.create({data:{name:"2026-2027",startDate:new Date("2026-06-01"),endDate:new Date("2027-05-31"),current:true}});
    const level = await prisma.classLevel.create({data:{name:"Pre-KG",code:"TEST-PREKG",academicYearId:year.id,capacity:1}});
    const section = await prisma.section.create({data:{name:"A",classLevelId:level.id,capacity:1}});
    const sequence = new SequenceService(prisma), enquiries = new EnquiriesService(prisma,sequence,{sendNewEnquiry:async()=>{}});
    const admissions = new AdmissionsService(prisma,sequence), crm = new CrmService(prisma,admissions), fees = new FeesService(prisma,sequence), students = new StudentsService(prisma,sequence);
    const capture = {parentName:"Integration Parent",studentName:"Integration Child",phone:"+91 98765 43210",interestedClass:"Pre-KG",academicYearId:year.id,consent:true};
    const [lead,repeat] = await Promise.all([enquiries.create(capture),enquiries.create(capture)]);
    assert.equal(lead.id,repeat.id); assert.equal(await prisma.enquiry.count(),1);
    await enquiries.bulkAssign([lead.id],staff.id,actor);
    await assert.rejects(() => enquiries.detail(lead.id,{...staff,id:teacher.id}),/not found/);
    await enquiries.addFollowUp(lead.id,{contactMethod:"CALL",notes:"Family contacted",status:"CONTACTED"},staff.name,staff);
    await enquiries.update(lead.id,{status:"QUALIFIED"},staff);
    const due = new Date(Date.now()+86400000).toISOString();
    const followUp = await crm.saveFollowUp(null,{enquiryId:lead.id,assignedStaffId:staff.id,dueAt:due,method:"CALL"},actor);
    const startAt = new Date(Date.now()+2*86400000),endAt=new Date(startAt.valueOf()+30*60000);
    const slot = await crm.saveSlot({startAt:startAt.toISOString(),endAt:endAt.toISOString(),capacity:1});
    const visit = await crm.saveVisit(null,{enquiryId:lead.id,assignedStaffId:staff.id,slotId:slot.id,startAt:startAt.toISOString(),endAt:endAt.toISOString()},actor);
    await assert.rejects(() => crm.saveVisit(null,{enquiryId:lead.id,assignedStaffId:staff.id,slotId:slot.id,startAt:startAt.toISOString(),endAt:endAt.toISOString()},actor),/capacity|already/);
    await crm.saveVisit(visit.id,{status:"COMPLETED",feedback:"School tour completed"},actor);
    const application = await admissions.create({studentName:capture.studentName,className:"Pre-KG",academicYearId:year.id,classLevelId:level.id,enquiryId:lead.id,childDob:"2022-01-01",parentName:capture.parentName,phone:capture.phone,address:"Integration-only address",emergencyContact:capture.phone,consent:true},actor);
    await assert.rejects(() => admissions.submit(application.id,staff),/documents missing/);
    for(const type of ["BIRTH_CERTIFICATE","CHILD_PHOTO"]) await crm.uploadDocument(application.id,type,{buffer:Buffer.from("%PDF-1.7 integration fixture"),originalname:type+".pdf"},staff);
    await admissions.submit(application.id,staff);
    await assert.rejects(() => admissions.review(application.id,{decision:"APPROVED"},staff),/manager/);
    await admissions.review(application.id,{decision:"APPROVED"},actor);
    const results = await Promise.all([admissions.confirm(application.id,{sectionId:section.id},actor),admissions.confirm(application.id,{sectionId:section.id},actor)]);
    assert.equal(results[0].student.id,results[1].student.id); assert.equal(await prisma.student.count(),1);
    assert.equal(await prisma.studentGuardian.count({where:{studentId:results[0].student.id,primary:true}}),1);
    assert.equal((await enquiries.detail(lead.id,actor)).status,"ENROLLED");
    await crm.saveFollowUp(followUp.id,{status:"COMPLETED",outcome:"Family enrolled"},staff);
    assert.equal((await prisma.followUpTask.findUnique({where:{id:followUp.id}})).status,"COMPLETED");
    const task = await crm.saveTask(null,{title:"Prepare learner record",assignedStaffId:admin.id,dueAt:due,studentId:results[0].student.id},actor);
    await crm.saveTask(task.id,{status:"COMPLETED"},actor);
    await crm.communication({enquiryId:lead.id,channel:"CALL",body:"Enrollment confirmation conversation",outcome:"Parent informed"},staff);
    assert.equal((await prisma.communicationLog.findFirst()).status,"RECORDED");
    const day = schoolDay();
    await crm.markAttendance({day,entries:[{studentId:results[0].student.id,status:"PRESENT"}]},{...teacher,sub:teacher.id});
    await crm.markAttendance({day,entries:[{studentId:results[0].student.id,status:"LATE"}]},{...teacher,sub:teacher.id});
    assert.equal(await prisma.attendanceRecord.count(),1);
    const fee = await fees.create({studentId:results[0].student.id,label:"Integration term fee",originalAmount:1000});
    const payment = await fees.pay({studentFeeId:fee.id,amount:400,method:"CASH"},actor);
    assert.equal((await fees.detail(fee.id)).balance.toString(),"600");
    const voids = await Promise.allSettled([fees.voidPayment(payment.id,"Integration correction",actor),fees.voidPayment(payment.id,"Repeated integration correction",actor)]);
    assert.equal(voids.filter(result=>result.status==="fulfilled").length,1);
    assert.equal((await fees.detail(fee.id)).paid.toString(),"0");
    await assert.rejects(() => fees.remove(fee.id),/history must be retained/);
    assert.equal(await prisma.payment.count(),1);
    const dashboard = await crm.dashboard({academicYearId:year.id},actor);
    assert.equal(dashboard.metrics.totalEnquiries,1); assert.equal(dashboard.conversionRate,100);
    const filtered = await crm.dashboard({academicYearId:year.id,program:"Other program"},actor);
    assert.equal(filtered.metrics.totalEnquiries,0); assert.equal(filtered.metrics.totalEnrolledStudents,0); assert.equal(filtered.metrics.todayTasks,0);
    assert.equal((await crm.listTasks({academicYearId:year.id},actor)).data.length,1);
    assert.equal((await crm.listTasks({program:"Other program"},actor)).data.length,0);
    assert.equal((await crm.report("admissions",{status:"ENROLLED",source:"WEBSITE",assignedStaffId:staff.id},actor)).data.length,1);
    assert.equal((await crm.report("admissions",{status:"APPROVED"},actor)).data.length,0);
    await enquiries.remove(lead.id,actor); assert.ok((await enquiries.detail(lead.id,actor)).archivedAt);
    assert.equal((await crm.report("enquiries",{academicYearId:year.id},actor)).data.length,1);
    await enquiries.archive(lead.id,false,actor);
    // A real PostgreSQL trigger forces the final enrollment audit to fail.
    await prisma.classLevel.update({where:{id:level.id},data:{capacity:2}});
    const secondLead = await enquiries.createInternal({...capture,studentName:"Second Integration Child",phone:"9876543211"},actor);
    const second = await admissions.create({studentName:"Second Integration Child",parentName:capture.parentName,phone:"9876543211",enquiryId:secondLead.id,className:"Pre-KG",academicYearId:year.id,classLevelId:level.id,childDob:"2022-01-01",address:"Integration address",emergencyContact:"9876543211",consent:true},actor);
    for(const type of ["BIRTH_CERTIFICATE","CHILD_PHOTO"]) await crm.uploadDocument(second.id,type,{buffer:Buffer.from("%PDF-1.7 integration fixture"),originalname:type+".pdf"},actor);
    await admissions.submit(second.id,actor); await admissions.review(second.id,{decision:"APPROVED"},actor);
    await control.query(`CREATE FUNCTION crm_test_reject_enrollment() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW."action" = 'ADMISSION_ENROLLED' THEN RAISE EXCEPTION 'forced audit failure'; END IF; RETURN NEW; END $$; CREATE TRIGGER crm_test_reject_enrollment BEFORE INSERT ON "AuditLog" FOR EACH ROW EXECUTE FUNCTION crm_test_reject_enrollment()`);
    try { await assert.rejects(() => admissions.confirm(second.id,{},actor),/forced audit failure/); }
    finally { await control.query('DROP TRIGGER crm_test_reject_enrollment ON "AuditLog"; DROP FUNCTION crm_test_reject_enrollment()'); }
    assert.equal(await prisma.student.count(),1);
    assert.equal((await prisma.admission.findUnique({where:{id:second.id}})).status,"APPROVED");
    await prisma.classLevel.update({where:{id:level.id},data:{capacity:1}});
    await assert.rejects(() => admissions.confirm(second.id,{},actor),/capacity is full/);
    await verifyResourcePersistence({prisma,crm,fees,actor,studentId:results[0].student.id,year,level});
    await students.remove(results[0].student.id);
    assert.equal(await prisma.student.count(),1); assert.equal(await prisma.studentGuardian.count(),1); assert.equal(await prisma.payment.count(),1);
    const migrations = await control.query('SELECT count(*)::int AS count FROM "_prisma_migrations" WHERE finished_at IS NOT NULL AND rolled_back_at IS NULL');
    assert.ok(migrations.rows[0].count>=8);
  } finally { if(prisma) await prisma.$disconnect(); await control.end(); }
  // Fixtures remain only in the explicitly supplied disposable database. No reset
  // or destructive cleanup is ever run against the configured school database.
});
